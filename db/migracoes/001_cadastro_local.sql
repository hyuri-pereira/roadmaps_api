ACTIVE BEFORE INSERT OR UPDATE POSITION 0
AS
BEGIN
  NEW.ATUALIZADO_EM = CURRENT_TIMESTAMP;
END^

/* Roadmap local (sem equipe) nao tem destinos a validar. */
CREATE OR ALTER TRIGGER BIU_RM_DESTINOS FOR ROADMAPS
ACTIVE BEFORE INSERT OR UPDATE POSITION 0
AS
BEGIN
  IF (NEW.ID_ASANA_EQUIPE IS NULL) THEN EXIT;

  IF (NOT EXISTS (SELECT 1 FROM EQUIPE_GESTORES
                   WHERE ID_ASANA_EQUIPE = NEW.ID_ASANA_EQUIPE
                     AND ID_USUARIO = NEW.ID_USUARIO_GESTOR
                     AND ATIVO = TRUE AND PODE_EDITAR = TRUE))
    THEN EXCEPTION EX_CONFIG;

  IF (NOT EXISTS (SELECT 1 FROM EQUIPE_DESTINOS
                   WHERE ID_ASANA_EQUIPE = NEW.ID_ASANA_EQUIPE))
    THEN EXCEPTION EX_CONFIG;

  IF (NOT EXISTS (SELECT 1 FROM ASANA_PROJETOS
                   WHERE ID_ASANA_PROJETO = NEW.ID_ASANA_PROJETO_CONTEXTO
                     AND ID_ASANA_EQUIPE = NEW.ID_ASANA_EQUIPE))
    THEN EXCEPTION EX_CONFIG;

  SELECT ID_PROJETO_SPRINT, ID_SECAO_A_FAZER, ID_PROJETO_BACKLOG, ID_SECAO_REFINO
    FROM EQUIPE_DESTINOS
   WHERE ID_ASANA_EQUIPE = NEW.ID_ASANA_EQUIPE
    INTO NEW.ID_ASANA_PROJETO_SPRINT, NEW.ID_ASANA_SECAO_SPRINT,
         NEW.ID_ASANA_PROJETO_BACKLOG, NEW.ID_ASANA_SECAO_BACKLOG;
END^

CREATE OR ALTER TRIGGER BIU_ROADMAPS FOR ROADMAPS
ACTIVE BEFORE INSERT OR UPDATE POSITION 2
AS
DECLARE VARIABLE V_ID BIGINT;
BEGIN
  NEW.ATUALIZADO_EM = CURRENT_TIMESTAMP;
  IF (UPDATING) THEN NEW.REVISAO = OLD.REVISAO + 1;

  /* Vincular e caminho sem volta: os cards ja podem existir no Asana. */
  IF (UPDATING AND OLD.ID_ASANA_EQUIPE IS NOT NULL AND NEW.ID_ASANA_EQUIPE IS NULL)
    THEN EXCEPTION EX_CONFIG;

  IF (NEW.ID_ASANA_CONEXAO IS NOT NULL) THEN
  BEGIN
    V_ID = NULL;
    SELECT ID_USUARIO FROM ASANA_CONEXOES
     WHERE ID_ASANA_CONEXAO = NEW.ID_ASANA_CONEXAO INTO :V_ID;
    IF (V_ID IS DISTINCT FROM NEW.ID_USUARIO_GESTOR) THEN EXCEPTION EX_PROJETOS_CONEXOES_DIF;
  END

  /* V_ID precisa ser zerada: um SELECT sem linhas mantem o valor anterior. */
  V_ID = NULL;
  SELECT ID_ASANA_PROJETO FROM ASANA_SECOES
   WHERE ID_ASANA_SECAO = NEW.ID_ASANA_SECAO_BACKLOG INTO :V_ID;
  IF (NEW.ID_ASANA_SECAO_BACKLOG IS NOT NULL
      AND V_ID IS DISTINCT FROM NEW.ID_ASANA_PROJETO_BACKLOG)
    THEN EXCEPTION EX_SECAO_FORA_PROJETO;

  V_ID = NULL;
  SELECT ID_ASANA_PROJETO FROM ASANA_SECOES
   WHERE ID_ASANA_SECAO = NEW.ID_ASANA_SECAO_SPRINT INTO :V_ID;
  IF (NEW.ID_ASANA_SECAO_SPRINT IS NOT NULL
      AND V_ID IS DISTINCT FROM NEW.ID_ASANA_PROJETO_SPRINT)
    THEN EXCEPTION EX_SECAO_FORA_PROJETO;
END^

/* Card de roadmap local nasce LOCAL; a exigencia de SPRINT configurada so
   vale para roadmap vinculado (no local o checkbox e so a intencao). */
CREATE OR ALTER TRIGGER BIU_ROADMAP_ITENS FOR ROADMAP_ITENS
ACTIVE BEFORE INSERT OR UPDATE POSITION 0
AS
DECLARE VARIABLE V_PROJETO_SPRINT BIGINT;
DECLARE VARIABLE V_EQUIPE BIGINT;
BEGIN
  IF (INSERTING) THEN NEW.CRIADO_EM = COALESCE(NEW.CRIADO_EM, CURRENT_TIMESTAMP);
  NEW.ATUALIZADO_EM = CURRENT_TIMESTAMP;
  IF (UPDATING) THEN NEW.REVISAO = OLD.REVISAO + 1;

  IF (NEW.CONCLUIDO = TRUE) THEN
    NEW.CONCLUIDO_EM = COALESCE(NEW.CONCLUIDO_EM, CURRENT_TIMESTAMP);
  ELSE
    NEW.CONCLUIDO_EM = NULL;

  V_PROJETO_SPRINT = NULL;
  V_EQUIPE = NULL;
  SELECT R.ID_ASANA_PROJETO_SPRINT, R.ID_ASANA_EQUIPE FROM ROADMAPS R
   WHERE R.ID_ROADMAP = NEW.ID_ROADMAP INTO :V_PROJETO_SPRINT, :V_EQUIPE;

  IF (V_EQUIPE IS NULL) THEN
  BEGIN
    IF (INSERTING) THEN NEW.SITUACAO_SINCRONIZACAO = 'LOCAL';
  END
  ELSE IF (NEW.ENTRAR_NA_SPRINT = TRUE AND V_PROJETO_SPRINT IS NULL) THEN
    EXCEPTION EX_SPRINT_NAO_CONFIGURADA;
END^

/* Titulo padrao com o nome do projeto LOCAL. */
CREATE OR ALTER TRIGGER BI_CARD_TITULO FOR ROADMAP_ITENS
ACTIVE BEFORE INSERT POSITION 2
AS
DECLARE VARIABLE V_NOME VARCHAR(200);
DECLARE VARIABLE V_RM VARCHAR(200);
BEGIN
  IF (NEW.ORIGEM_ULTIMA_ALTERACAO = 'ASANA') THEN EXIT;

  SELECT P.NOME, R.TITULO
    FROM ROADMAPS R
    JOIN PROJETOS P ON P.ID_PROJETO = R.ID_PROJETO
   WHERE R.ID_ROADMAP = NEW.ID_ROADMAP
    INTO :V_NOME, :V_RM;

  NEW.TITULO = V_NOME || ' - ' ||
               CASE NEW.PRIORIDADE WHEN 1 THEN 'URGENTE' WHEN 2 THEN 'ALTA'
                                   WHEN 3 THEN 'MEDIA' ELSE 'BAIXA' END;

  IF (NEW.DATA_LIMITE IS NOT NULL) THEN
    NEW.TITULO = NEW.TITULO || ' - ' ||
                 LPAD(CAST(EXTRACT(DAY FROM NEW.DATA_LIMITE) AS VARCHAR(2)), 2, '0') || '/' ||
                 LPAD(CAST(EXTRACT(MONTH FROM NEW.DATA_LIMITE) AS VARCHAR(2)), 2, '0') || '/' ||
                 CAST(EXTRACT(YEAR FROM NEW.DATA_LIMITE) AS VARCHAR(4));

  NEW.TITULO = NEW.TITULO || ' - ' || V_RM;
  NEW.TITULO_GERADO = NEW.TITULO;
END^

/* Roadmap local: nada vai para a fila. */
CREATE OR ALTER TRIGGER AI_ROADMAP_ITEM_FILA FOR ROADMAP_ITENS
ACTIVE AFTER INSERT POSITION 10
AS
DECLARE VARIABLE V_CONEXAO BIGINT;
BEGIN
  IF (NEW.ASANA_TAREFA_GID IS NOT NULL) THEN EXIT;

  V_CONEXAO = NULL;
  SELECT R.ID_ASANA_CONEXAO FROM ROADMAPS R
   WHERE R.ID_ROADMAP = NEW.ID_ROADMAP INTO :V_CONEXAO;
  IF (V_CONEXAO IS NULL) THEN EXIT;

  INSERT INTO INTEGRACAO_FILA (
      ID_ASANA_CONEXAO, TIPO_OPERACAO, TIPO_ENTIDADE_LOCAL,
      ID_ENTIDADE_LOCAL, CHAVE_IDEMPOTENCIA, PRIORIDADE_FILA
  ) VALUES (
      :V_CONEXAO, 'CRIAR_TAREFA', 'ROADMAP_ITEM',
      NEW.ID_ROADMAP_ITEM, 'CRIAR_TAREFA:' || NEW.ID_ROADMAP_ITEM, 3
  );
END^

SET TERM ;^
COMMIT;

