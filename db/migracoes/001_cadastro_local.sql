/* =====================================================================
   MIGRACAO 001 - CADASTRO LOCAL (projetos, roadmaps e cards sem Asana)
   Banco-alvo: Firebird 5.0 | SQL Dialect 3

   O que muda
   - Nova tabela PROJETOS: projeto local, com vinculo OPCIONAL a um projeto
     do catalogo do Asana (ID_ASANA_PROJETO).
   - ROADMAPS ganha ID_PROJETO (obrigatorio) e as colunas do Asana
     (conexao, equipe, projeto de contexto, backlog) passam a aceitar NULL.
     Roadmap sem equipe = roadmap LOCAL: nada vai para a fila.
   - Vincular um roadmap local ao Asana = preencher conexao, equipe e projeto
     de contexto. A partir dai as regras antigas valem e os cards existentes
     sao enfileirados pela aplicacao (SP_SOLICITAR_SYNC_ITEM).
   - Card de roadmap local nasce com SITUACAO_SINCRONIZACAO = 'LOCAL'.
   - O titulo padrao do card usa o nome do projeto LOCAL.

   Roadmaps existentes continuam vinculados: cada projeto do Asana usado como
   contexto vira um projeto local ja vinculado a ele.

   Idempotencia: este script NAO e reexecutavel. Aplique uma unica vez, com a
   API parada, depois de um backup (gbak).
   ===================================================================== */

SET SQL DIALECT 3;
SET NAMES UTF8;
SET AUTODDL ON;

/* ------------------------------------------------------ 1. PROJETOS */

CREATE TABLE PROJETOS (
    ID_PROJETO          BIGINT GENERATED ALWAYS AS IDENTITY,
    NOME                VARCHAR(200) NOT NULL,
    DESCRICAO           BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
    COR                 VARCHAR(30),
    ID_USUARIO_CRIADOR  BIGINT NOT NULL,
    ID_ASANA_PROJETO    BIGINT,
    ARQUIVADO           BOOLEAN DEFAULT FALSE NOT NULL,
    CRIADO_EM           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_PROJETOS PRIMARY KEY (ID_PROJETO),
    CONSTRAINT FK_PROJETO_CRIADOR FOREIGN KEY (ID_USUARIO_CRIADOR)
        REFERENCES USUARIOS (ID_USUARIO),
    CONSTRAINT FK_PROJETO_ASANA FOREIGN KEY (ID_ASANA_PROJETO)
        REFERENCES ASANA_PROJETOS (ID_ASANA_PROJETO) ON DELETE SET NULL,
    /* Um projeto do Asana corresponde a no maximo um projeto local.
       UNIQUE aceita varios NULL (projetos so locais). */
    CONSTRAINT UK_PROJETO_ASANA UNIQUE (ID_ASANA_PROJETO)
);

CREATE INDEX IX_PROJETOS_NOME ON PROJETOS (NOME);

/* -------------------------------------------- 2. ROADMAPS / CARDS */

ALTER TABLE ROADMAPS ADD ID_PROJETO BIGINT;
ALTER TABLE ROADMAPS ALTER ID_ASANA_CONEXAO DROP NOT NULL;
ALTER TABLE ROADMAPS ALTER ID_ASANA_EQUIPE DROP NOT NULL;
ALTER TABLE ROADMAPS ALTER ID_ASANA_PROJETO_CONTEXTO DROP NOT NULL;
ALTER TABLE ROADMAPS ALTER ID_ASANA_PROJETO_BACKLOG DROP NOT NULL;

ALTER TABLE ROADMAP_ITENS DROP CONSTRAINT CK_ROADMAP_ITEM_SYNC;
ALTER TABLE ROADMAP_ITENS ADD CONSTRAINT CK_ROADMAP_ITEM_SYNC CHECK (
    SITUACAO_SINCRONIZACAO IN (
        'LOCAL', 'PENDENTE_CRIACAO', 'PENDENTE_ATUALIZACAO', 'SINCRONIZADO',
        'PENDENTE_EXCLUSAO', 'CONFLITO', 'ERRO'
    )
);

COMMIT;

/* ------------------------------------ 3. BACKFILL DOS EXISTENTES */

/* As triggers de ROADMAPS revalidariam equipe/gestor e subiriam a revisao;
   aqui so estamos preenchendo a coluna nova. */
ALTER TRIGGER BIU_RM_DESTINOS INACTIVE;
ALTER TRIGGER BIU_ROADMAPS INACTIVE;
ALTER TRIGGER AU_RM_NOTIF INACTIVE;
COMMIT;

INSERT INTO PROJETOS (NOME, DESCRICAO, COR, ID_USUARIO_CRIADOR, ID_ASANA_PROJETO)
SELECT P.NOME, P.DESCRICAO, P.COR,
       (SELECT MIN(R2.ID_USUARIO_GESTOR) FROM ROADMAPS R2
         WHERE R2.ID_ASANA_PROJETO_CONTEXTO = P.ID_ASANA_PROJETO),
       P.ID_ASANA_PROJETO
  FROM ASANA_PROJETOS P
 WHERE EXISTS (SELECT 1 FROM ROADMAPS R
                WHERE R.ID_ASANA_PROJETO_CONTEXTO = P.ID_ASANA_PROJETO);

UPDATE ROADMAPS R
   SET ID_PROJETO = (SELECT X.ID_PROJETO FROM PROJETOS X
                      WHERE X.ID_ASANA_PROJETO = R.ID_ASANA_PROJETO_CONTEXTO);

COMMIT;

ALTER TRIGGER BIU_RM_DESTINOS ACTIVE;
ALTER TRIGGER BIU_ROADMAPS ACTIVE;
ALTER TRIGGER AU_RM_NOTIF ACTIVE;
COMMIT;

ALTER TABLE ROADMAPS ALTER ID_PROJETO SET NOT NULL;
ALTER TABLE ROADMAPS ADD CONSTRAINT FK_ROADMAP_PROJETO FOREIGN KEY (ID_PROJETO)
    REFERENCES PROJETOS (ID_PROJETO);

/* Local: nenhum dado do Asana. Vinculado: conexao, equipe e contexto juntos
   (o backlog e preenchido pela BIU_RM_DESTINOS antes do CHECK). */
ALTER TABLE ROADMAPS ADD CONSTRAINT CK_ROADMAP_VINCULO CHECK (
    (ID_ASANA_EQUIPE IS NULL AND ID_ASANA_CONEXAO IS NULL
     AND ID_ASANA_PROJETO_CONTEXTO IS NULL)
    OR
    (ID_ASANA_EQUIPE IS NOT NULL AND ID_ASANA_CONEXAO IS NOT NULL
     AND ID_ASANA_PROJETO_CONTEXTO IS NOT NULL AND ID_ASANA_PROJETO_BACKLOG IS NOT NULL)
);

CREATE INDEX IX_ROADMAPS_PROJETO ON ROADMAPS (ID_PROJETO, EXCLUIDO_EM);

COMMIT;

