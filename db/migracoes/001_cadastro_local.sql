CREATE OR ALTER PROCEDURE SP_MONTAR_CARD (P_ID_ITEM BIGINT)
RETURNS (
    TITULO        VARCHAR(1000),
    CORPO         BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
    PROJETO_GID   VARCHAR(64),
    SECAO_GID     VARCHAR(64)
)
AS
DECLARE VARIABLE V_PROJ VARCHAR(200);
DECLARE VARIABLE V_RM VARCHAR(200);
DECLARE VARIABLE V_DATA DATE;
DECLARE VARIABLE V_PRI SMALLINT;
DECLARE VARIABLE V_P BIGINT;
DECLARE VARIABLE V_S BIGINT;
DECLARE VARIABLE V_URL VARCHAR(2048);
DECLARE VARIABLE V_ROTULO VARCHAR(255);
DECLARE VARIABLE V_QTD INTEGER;
BEGIN
  SELECT P.NOME, R.TITULO, I.DATA_LIMITE, I.PRIORIDADE,
         COALESCE(I.DESCRICAO_BASE, I.DESCRICAO),
         IIF(I.ENTRAR_NA_SPRINT, R.ID_ASANA_PROJETO_SPRINT, R.ID_ASANA_PROJETO_BACKLOG),
         IIF(I.ENTRAR_NA_SPRINT, R.ID_ASANA_SECAO_SPRINT, R.ID_ASANA_SECAO_BACKLOG)
    FROM ROADMAP_ITENS I
    JOIN ROADMAPS R ON R.ID_ROADMAP = I.ID_ROADMAP
    JOIN PROJETOS P ON P.ID_PROJETO = R.ID_PROJETO
   WHERE I.ID_ROADMAP_ITEM = :P_ID_ITEM
    INTO :V_PROJ, :V_RM, :V_DATA, :V_PRI, :CORPO, :V_P, :V_S;

  IF (ROW_COUNT = 0) THEN EXCEPTION EX_CONFIG;

  TITULO = V_PROJ || ' - ' ||
           CASE V_PRI WHEN 1 THEN 'URGENTE' WHEN 2 THEN 'ALTA'
                      WHEN 3 THEN 'MEDIA' ELSE 'BAIXA' END;

  IF (V_DATA IS NOT NULL) THEN
    TITULO = TITULO || ' - ' ||
             LPAD(CAST(EXTRACT(DAY FROM V_DATA) AS VARCHAR(2)), 2, '0') || '/' ||
             LPAD(CAST(EXTRACT(MONTH FROM V_DATA) AS VARCHAR(2)), 2, '0') || '/' ||
             CAST(EXTRACT(YEAR FROM V_DATA) AS VARCHAR(4));

  TITULO = TITULO || ' - ' || V_RM;

  SELECT COUNT(*) FROM ITEM_REFERENCIAS
   WHERE ID_ROADMAP_ITEM = :P_ID_ITEM INTO :V_QTD;

  CORPO = COALESCE(CORPO, '');

  IF (V_QTD > 0) THEN
  BEGIN
    CORPO = CORPO || ASCII_CHAR(10) || ASCII_CHAR(10) || 'Links de referencia:';
    FOR SELECT URL_REFERENCIA, ROTULO
          FROM ITEM_REFERENCIAS
         WHERE ID_ROADMAP_ITEM = :P_ID_ITEM
         ORDER BY ORDEM, ID_REFERENCIA
          INTO :V_URL, :V_ROTULO
    DO
      IF (V_ROTULO IS NULL OR V_ROTULO = '') THEN
        CORPO = CORPO || ASCII_CHAR(10) || '- ' || V_URL;
      ELSE
        CORPO = CORPO || ASCII_CHAR(10) || '- ' || V_ROTULO || ': ' || V_URL;
  END

  SELECT ASANA_GID FROM ASANA_PROJETOS WHERE ID_ASANA_PROJETO = :V_P INTO :PROJETO_GID;
  SELECT ASANA_GID FROM ASANA_SECOES WHERE ID_ASANA_SECAO = :V_S INTO :SECAO_GID;
  SUSPEND;
END^

/* Card de roadmap local nao tem para onde sincronizar. */
CREATE OR ALTER PROCEDURE SP_SOLICITAR_SYNC_ITEM (P_ID_ROADMAP_ITEM BIGINT)
AS
DECLARE VARIABLE V_CONEXAO BIGINT;
DECLARE VARIABLE V_GID VARCHAR(64);
DECLARE VARIABLE V_CHAVE VARCHAR(150);
DECLARE VARIABLE V_EXISTE INTEGER;
BEGIN
  SELECT R.ID_ASANA_CONEXAO, I.ASANA_TAREFA_GID
    FROM ROADMAP_ITENS I
    JOIN ROADMAPS R ON R.ID_ROADMAP = I.ID_ROADMAP
   WHERE I.ID_ROADMAP_ITEM = :P_ID_ROADMAP_ITEM AND I.EXCLUIDO_EM IS NULL
    INTO :V_CONEXAO, :V_GID;

  IF (ROW_COUNT = 0) THEN EXIT;
  IF (V_CONEXAO IS NULL) THEN EXIT;

  IF (V_GID IS NULL) THEN
    V_CHAVE = 'CRIAR_TAREFA:' || P_ID_ROADMAP_ITEM;
  ELSE
    SELECT 'ATUALIZAR_TAREFA:' || ID_ROADMAP_ITEM || ':' || REVISAO
      FROM ROADMAP_ITENS
     WHERE ID_ROADMAP_ITEM = :P_ID_ROADMAP_ITEM
      INTO :V_CHAVE;

  SELECT COUNT(*) FROM INTEGRACAO_FILA F
   WHERE F.CHAVE_IDEMPOTENCIA = :V_CHAVE INTO :V_EXISTE;

  IF (V_EXISTE = 0) THEN
    INSERT INTO INTEGRACAO_FILA (
        ID_ASANA_CONEXAO, TIPO_OPERACAO, TIPO_ENTIDADE_LOCAL,
        ID_ENTIDADE_LOCAL, RECURSO_GID, CHAVE_IDEMPOTENCIA, PRIORIDADE_FILA
    ) VALUES (
        :V_CONEXAO,
        IIF(:V_GID IS NULL, 'CRIAR_TAREFA', 'ATUALIZAR_TAREFA'),
        'ROADMAP_ITEM', :P_ID_ROADMAP_ITEM, :V_GID, :V_CHAVE, 3
    );
  ELSE
    UPDATE INTEGRACAO_FILA F
       SET SITUACAO = 'PENDENTE',
           TENTATIVAS = 0,
           PROXIMA_TENTATIVA_EM = CURRENT_TIMESTAMP,
           LOCK_TOKEN = NULL,
           BLOQUEADO_ATE = NULL,
           BLOQUEADO_POR = NULL,
           ULTIMO_ERRO = NULL,
           PROCESSADO_EM = NULL
     WHERE F.CHAVE_IDEMPOTENCIA = :V_CHAVE
       AND F.SITUACAO NOT IN ('PENDENTE', 'PROCESSANDO');

  UPDATE ROADMAP_ITENS I
     SET SITUACAO_SINCRONIZACAO =
           IIF(:V_GID IS NULL, 'PENDENTE_CRIACAO', 'PENDENTE_ATUALIZACAO'),
         ORIGEM_ULTIMA_ALTERACAO = 'SISTEMA'
   WHERE I.ID_ROADMAP_ITEM = :P_ID_ROADMAP_ITEM;
END^

/* Roadmap local conclui na hora: nao ha Asana para confirmar. */
CREATE OR ALTER PROCEDURE SP_SOLICITAR_CONCLUSAO_ROADMAP (
    P_ID_ROADMAP BIGINT,
    P_ID_USUARIO BIGINT
)
AS
DECLARE VARIABLE V_SITUACAO VARCHAR(25);
DECLARE VARIABLE V_TOTAL INTEGER;
DECLARE VARIABLE V_ID_ITEM BIGINT;
DECLARE VARIABLE V_GID VARCHAR(64);
DECLARE VARIABLE V_REVISAO BIGINT;
DECLARE VARIABLE V_CONEXAO BIGINT;
DECLARE VARIABLE V_CHAVE VARCHAR(150);
DECLARE VARIABLE V_EXISTE INTEGER;
DECLARE VARIABLE V_PENDENTES INTEGER;
BEGIN
  SELECT R.SITUACAO, R.ID_ASANA_CONEXAO
    FROM ROADMAPS R
   WHERE R.ID_ROADMAP = :P_ID_ROADMAP AND R.EXCLUIDO_EM IS NULL
    INTO :V_SITUACAO, :V_CONEXAO;

  IF (ROW_COUNT = 0) THEN EXCEPTION EX_ROADMAP_INEXISTENTE;
  IF (V_SITUACAO IN ('CONCLUIDO', 'CANCELADO')) THEN EXCEPTION EX_ROADMAP_JA_ENCERRADO;

  SELECT COUNT(*) FROM ROADMAP_ITENS I
   WHERE I.ID_ROADMAP = :P_ID_ROADMAP AND I.EXCLUIDO_EM IS NULL INTO :V_TOTAL;
  IF (V_TOTAL = 0) THEN EXCEPTION EX_ROADMAP_SEM_ITENS;

  SELECT COUNT(*) FROM ROADMAP_ITENS I
   WHERE I.ID_ROADMAP = :P_ID_ROADMAP AND I.EXCLUIDO_EM IS NULL AND I.CONCLUIDO = FALSE
    INTO :V_PENDENTES;

  IF (V_PENDENTES = 0 OR V_CONEXAO IS NULL) THEN
  BEGIN
    UPDATE ROADMAP_ITENS I
       SET CONCLUIDO = TRUE
     WHERE I.ID_ROADMAP = :P_ID_ROADMAP
       AND I.EXCLUIDO_EM IS NULL AND I.CONCLUIDO = FALSE;

    UPDATE ROADMAPS R
       SET SITUACAO = 'CONCLUIDO',
           CONCLUIDO_EM = COALESCE(R.CONCLUIDO_EM, CURRENT_TIMESTAMP)
     WHERE R.ID_ROADMAP = :P_ID_ROADMAP;

    INSERT INTO AUDITORIA_EVENTOS (
        ID_USUARIO, TIPO_ENTIDADE, ID_ENTIDADE, ACAO, ORIGEM, RESUMO
    ) VALUES (
        :P_ID_USUARIO, 'ROADMAP', :P_ID_ROADMAP, 'CONCLUIR', 'USUARIO',
        IIF(:V_PENDENTES = 0,
            'Roadmap concluido; todos os cards ja estavam concluidos',
            'Roadmap local concluido junto com os cards pendentes')
    );
    EXIT;
  END

  FOR SELECT I.ID_ROADMAP_ITEM, I.ASANA_TAREFA_GID, I.REVISAO
        FROM ROADMAP_ITENS I
       WHERE I.ID_ROADMAP = :P_ID_ROADMAP
         AND I.EXCLUIDO_EM IS NULL
         AND I.CONCLUIDO = FALSE
        INTO :V_ID_ITEM, :V_GID, :V_REVISAO
  DO
  BEGIN
    UPDATE ROADMAP_ITENS I
       SET CONCLUSAO_SOLICITADA = TRUE
     WHERE I.ID_ROADMAP_ITEM = :V_ID_ITEM;

    V_CHAVE = 'CONCLUIR_TAREFA:' || V_ID_ITEM || ':' || V_REVISAO;

    SELECT COUNT(*) FROM INTEGRACAO_FILA F
     WHERE F.CHAVE_IDEMPOTENCIA = :V_CHAVE INTO :V_EXISTE;

    IF (V_EXISTE = 0) THEN
      INSERT INTO INTEGRACAO_FILA (
          ID_ASANA_CONEXAO, TIPO_OPERACAO, TIPO_ENTIDADE_LOCAL,
          ID_ENTIDADE_LOCAL, RECURSO_GID, CHAVE_IDEMPOTENCIA, PRIORIDADE_FILA
      ) VALUES (
          :V_CONEXAO, 'CONCLUIR_TAREFA', 'ROADMAP_ITEM',
          :V_ID_ITEM, :V_GID, :V_CHAVE, 1
      );
  END

  UPDATE ROADMAPS R
     SET SITUACAO = 'CONCLUSAO_PENDENTE',
         CONCLUSAO_SOLICITADA_EM = CURRENT_TIMESTAMP
   WHERE R.ID_ROADMAP = :P_ID_ROADMAP;

  INSERT INTO AUDITORIA_EVENTOS (
      ID_USUARIO, TIPO_ENTIDADE, ID_ENTIDADE, ACAO, ORIGEM, RESUMO
  ) VALUES (
      :P_ID_USUARIO, 'ROADMAP', :P_ID_ROADMAP, 'SOLICITAR_CONCLUSAO', 'USUARIO',
      'Conclusao solicitada para todos os cards'
  );
END^

/* Card local: so a exclusao logica, sem pedido remoto. */
CREATE OR ALTER PROCEDURE SP_EXCLUIR_ITEM (P_ID_ITEM BIGINT)
AS
DECLARE VARIABLE V_CONEXAO BIGINT;
DECLARE VARIABLE V_GID VARCHAR(64);
DECLARE VARIABLE V_EXISTE INTEGER;
BEGIN
  SELECT R.ID_ASANA_CONEXAO, I.ASANA_TAREFA_GID
    FROM ROADMAP_ITENS I
    JOIN ROADMAPS R ON R.ID_ROADMAP = I.ID_ROADMAP
   WHERE I.ID_ROADMAP_ITEM = :P_ID_ITEM AND I.EXCLUIDO_EM IS NULL
    INTO :V_CONEXAO, :V_GID;

  IF (ROW_COUNT = 0) THEN EXIT;

  IF (V_CONEXAO IS NULL) THEN
  BEGIN
    UPDATE ROADMAP_ITENS SET EXCLUIDO_EM = CURRENT_TIMESTAMP
     WHERE ID_ROADMAP_ITEM = :P_ID_ITEM;
    EXIT;
  END

  UPDATE ROADMAP_ITENS
     SET EXCLUIDO_EM = CURRENT_TIMESTAMP,
         SITUACAO_SINCRONIZACAO = 'PENDENTE_EXCLUSAO'
   WHERE ID_ROADMAP_ITEM = :P_ID_ITEM;

  UPDATE INTEGRACAO_FILA
     SET SITUACAO = 'CANCELADO', PROCESSADO_EM = CURRENT_TIMESTAMP
   WHERE CHAVE_IDEMPOTENCIA = 'CRIAR_TAREFA:' || :P_ID_ITEM
     AND SITUACAO = 'PENDENTE';

  SELECT COUNT(*) FROM INTEGRACAO_FILA
   WHERE CHAVE_IDEMPOTENCIA = 'EXCLUIR_ITEM:' || :P_ID_ITEM INTO :V_EXISTE;

  IF (V_EXISTE = 0) THEN
    INSERT INTO INTEGRACAO_FILA (
        ID_ASANA_CONEXAO, TIPO_OPERACAO, TIPO_ENTIDADE_LOCAL,
        ID_ENTIDADE_LOCAL, RECURSO_GID, CHAVE_IDEMPOTENCIA, PRIORIDADE_FILA
    ) VALUES (
        :V_CONEXAO, 'EXCLUIR_TAREFA', 'ROADMAP_ITEM',
        :P_ID_ITEM, :V_GID, 'EXCLUIR_ITEM:' || :P_ID_ITEM, 2
    );
END^

SET TERM ;^
COMMIT;

/* ---------------------------------------------------- 6. VIEWS */

CREATE VIEW VW_PROJETOS_PROGRESSO AS
SELECT
    P.ID_PROJETO,
    P.NOME,
    P.COR,
    P.ARQUIVADO,
    P.ID_ASANA_PROJETO,
    P.ID_USUARIO_CRIADOR,
    COUNT(V.ID_ROADMAP) AS TOTAL_ROADMAPS,
    SUM(CASE WHEN V.SITUACAO = 'CONCLUIDO' THEN 1 ELSE 0 END) AS ROADMAPS_CONCLUIDOS,
    SUM(CASE WHEN V.SITUACAO IN ('RASCUNHO', 'PLANEJADO', 'EM_ANDAMENTO', 'CONCLUSAO_PENDENTE')
             THEN 1 ELSE 0 END) AS ROADMAPS_ATIVOS,
    COALESCE(SUM(V.TOTAL_CARDS), 0) AS TOTAL_CARDS,
    COALESCE(SUM(V.CARDS_CONCLUIDOS), 0) AS CARDS_CONCLUIDOS,
    CAST(
      CASE
        WHEN COALESCE(SUM(V.TOTAL_CARDS), 0) = 0 THEN 0
        ELSE 100.00 * SUM(V.CARDS_CONCLUIDOS) / SUM(V.TOTAL_CARDS)
      END AS NUMERIC(6,2)
    ) AS PERCENTUAL_GERAL
FROM PROJETOS P
LEFT JOIN ROADMAPS R
       ON R.ID_PROJETO = P.ID_PROJETO AND R.EXCLUIDO_EM IS NULL
LEFT JOIN VW_ROADMAP_PROGRESSO V
       ON V.ID_ROADMAP = R.ID_ROADMAP
GROUP BY P.ID_PROJETO, P.NOME, P.COR, P.ARQUIVADO, P.ID_ASANA_PROJETO, P.ID_USUARIO_CRIADOR;

COMMIT;
