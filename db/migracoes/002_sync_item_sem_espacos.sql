/* =====================================================================
   MIGRACAO 002 - SP_SOLICITAR_SYNC_ITEM sem espacos a direita

   IIF entre dois literais devolve CHAR(n), completado com espacos. A
   procedure gravava 'CRIAR_TAREFA    ' em INTEGRACAO_FILA.TIPO_OPERACAO e
   'PENDENTE_CRIACAO    ' em ROADMAP_ITENS.SITUACAO_SINCRONIZACAO; o worker
   compara o tipo exato e cancelava o job como "nao implementado".
   O CAST para VARCHAR preserva o texto sem o preenchimento.
   ===================================================================== */

SET SQL DIALECT 3;
SET NAMES UTF8;
SET AUTODDL ON;

SET TERM ^;

CREATE OR ALTER PROCEDURE SP_SOLICITAR_SYNC_ITEM (P_ID_ROADMAP_ITEM BIGINT)
AS
DECLARE VARIABLE V_CONEXAO BIGINT;
DECLARE VARIABLE V_GID VARCHAR(64);
DECLARE VARIABLE V_CHAVE VARCHAR(150);
DECLARE VARIABLE V_EXISTE INTEGER;
BEGIN
  SELECT R.ID_ASANA_CONEXAO, I.ASANA_TAREFA_GID
    FROM ROADMAP_ITENS I
    JOIN ROADMAPS R ON R.ID_ROADMAP = I.ID_ROADMAP
   WHERE I.ID_ROADMAP_ITEM = :P_ID_ROADMAP_ITEM AND I.EXCLUIDO_EM IS NULL
    INTO :V_CONEXAO, :V_GID;

  IF (ROW_COUNT = 0) THEN EXIT;
  IF (V_CONEXAO IS NULL) THEN EXIT;

  IF (V_GID IS NULL) THEN
    V_CHAVE = 'CRIAR_TAREFA:' || P_ID_ROADMAP_ITEM;
  ELSE
    SELECT 'ATUALIZAR_TAREFA:' || ID_ROADMAP_ITEM || ':' || REVISAO
      FROM ROADMAP_ITENS
     WHERE ID_ROADMAP_ITEM = :P_ID_ROADMAP_ITEM
      INTO :V_CHAVE;

  SELECT COUNT(*) FROM INTEGRACAO_FILA F
   WHERE F.CHAVE_IDEMPOTENCIA = :V_CHAVE INTO :V_EXISTE;

  IF (V_EXISTE = 0) THEN
    INSERT INTO INTEGRACAO_FILA (
        ID_ASANA_CONEXAO, TIPO_OPERACAO, TIPO_ENTIDADE_LOCAL,
        ID_ENTIDADE_LOCAL, RECURSO_GID, CHAVE_IDEMPOTENCIA, PRIORIDADE_FILA
    ) VALUES (
        :V_CONEXAO,
        CAST(IIF(:V_GID IS NULL, 'CRIAR_TAREFA', 'ATUALIZAR_TAREFA') AS VARCHAR(30)),
        'ROADMAP_ITEM', :P_ID_ROADMAP_ITEM, :V_GID, :V_CHAVE, 3
    );
  ELSE
    UPDATE INTEGRACAO_FILA F
       SET SITUACAO = 'PENDENTE',
           TENTATIVAS = 0,
           PROXIMA_TENTATIVA_EM = CURRENT_TIMESTAMP,
           LOCK_TOKEN = NULL,
           BLOQUEADO_ATE = NULL,
           BLOQUEADO_POR = NULL,
           ULTIMO_ERRO = NULL,
           PROCESSADO_EM = NULL
     WHERE F.CHAVE_IDEMPOTENCIA = :V_CHAVE
       AND F.SITUACAO NOT IN ('PENDENTE', 'PROCESSANDO');

  UPDATE ROADMAP_ITENS I
     SET SITUACAO_SINCRONIZACAO =
           CAST(IIF(:V_GID IS NULL, 'PENDENTE_CRIACAO', 'PENDENTE_ATUALIZACAO') AS VARCHAR(25)),
         ORIGEM_ULTIMA_ALTERACAO = 'SISTEMA'
   WHERE I.ID_ROADMAP_ITEM = :P_ID_ROADMAP_ITEM;
END^

SET TERM ;^
COMMIT;

/* Corrige o que ja tenha sido gravado com preenchimento. Jobs cancelados
   como "nao implementado" voltam para a fila. */
UPDATE INTEGRACAO_FILA
   SET SITUACAO = 'PENDENTE', TENTATIVAS = 0, PROXIMA_TENTATIVA_EM = CURRENT_TIMESTAMP,
       ULTIMO_ERRO = NULL, PROCESSADO_EM = NULL
 WHERE CHAR_LENGTH(TIPO_OPERACAO) <> CHAR_LENGTH(TRIM(TIPO_OPERACAO)) AND SITUACAO = 'CANCELADO'
   AND ULTIMO_ERRO LIKE '%nao implementada%';
UPDATE INTEGRACAO_FILA SET TIPO_OPERACAO = TRIM(TIPO_OPERACAO)
 WHERE CHAR_LENGTH(TIPO_OPERACAO) <> CHAR_LENGTH(TRIM(TIPO_OPERACAO));
UPDATE ROADMAP_ITENS SET SITUACAO_SINCRONIZACAO = TRIM(SITUACAO_SINCRONIZACAO)
 WHERE CHAR_LENGTH(SITUACAO_SINCRONIZACAO) <> CHAR_LENGTH(TRIM(SITUACAO_SINCRONIZACAO));
COMMIT;
