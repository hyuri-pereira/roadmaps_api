        REFERENCES ASANA_CONEXOES (ID_ASANA_CONEXAO),
    CONSTRAINT FK_RM_EQUIPE FOREIGN KEY (ID_ASANA_EQUIPE)
        REFERENCES ASANA_EQUIPES (ID_ASANA_EQUIPE),
    CONSTRAINT FK_ROADMAP_GESTOR FOREIGN KEY (ID_USUARIO_GESTOR)
        REFERENCES USUARIOS (ID_USUARIO),
    CONSTRAINT FK_ROADMAP_PROJ_CONTEXTO FOREIGN KEY (ID_ASANA_PROJETO_CONTEXTO)
        REFERENCES ASANA_PROJETOS (ID_ASANA_PROJETO),
    CONSTRAINT FK_ROADMAP_PROJ_BACKLOG FOREIGN KEY (ID_ASANA_PROJETO_BACKLOG)
