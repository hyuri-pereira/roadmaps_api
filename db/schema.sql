        DATA_FIM >= DATEADD(7 DAY TO DATA_INICIO)
        AND DATA_FIM <= DATEADD(3 MONTH TO DATA_INICIO)
    ),
    CONSTRAINT CK_ROADMAP_SITUACAO CHECK (
        SITUACAO IN (
