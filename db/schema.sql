                 LPAD(CAST(EXTRACT(MONTH FROM NEW.DATA_LIMITE) AS VARCHAR(2)), 2, '0') || '/' ||
                 CAST(EXTRACT(YEAR FROM NEW.DATA_LIMITE) AS VARCHAR(4));

  NEW.TITULO = NEW.TITULO || ' - ' || V_RM;
