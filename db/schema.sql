    ID_OAUTH_ESTADO         BIGINT GENERATED ALWAYS AS IDENTITY,
    PROVEDOR                VARCHAR(20) NOT NULL,
    ESTADO                  VARCHAR(128) CHARACTER SET ASCII NOT NULL,
    CODE_VERIFIER           VARCHAR(255) CHARACTER SET ASCII,
    ID_USUARIO              BIGINT,
    REDIRECIONAR_PARA       VARCHAR(1000),
    DADOS_JSON              BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
    EXPIRA_EM               TIMESTAMP NOT NULL,
    CONSUMIDO_EM            TIMESTAMP,
    CRIADO_EM               TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_OAUTH_ESTADOS PRIMARY KEY (ID_OAUTH_ESTADO),
    CONSTRAINT UK_OAUTH_ESTADO UNIQUE (ESTADO),
    CONSTRAINT FK_OAUTH_ESTADO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT CK_OAUTH_ESTADO_PROVEDOR CHECK (PROVEDOR IN ('GOOGLE', 'ASANA'))
);

