    CONSTRAINT FK_ROADMAP_PROJ_SPRINT FOREIGN KEY (ID_ASANA_PROJETO_SPRINT)
        REFERENCES ASANA_PROJETOS (ID_ASANA_PROJETO),
    CONSTRAINT FK_ROADMAP_SECAO_SPRINT FOREIGN KEY (ID_ASANA_SECAO_SPRINT)
        REFERENCES ASANA_SECOES (ID_ASANA_SECAO),
