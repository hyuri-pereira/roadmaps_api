CREATE TABLE ROADMAPS (
    ID_ROADMAP                    BIGINT GENERATED ALWAYS AS IDENTITY,
    ID_USUARIO_GESTOR             BIGINT NOT NULL,
    ID_ASANA_CONEXAO              BIGINT NOT NULL,
