CREATE VIEW VW_ROADMAP_PROGRESSO AS
SELECT
    R.ID_ROADMAP,
    R.ID_USUARIO_GESTOR,
    R.ID_ASANA_EQUIPE,
    R.ID_ASANA_PROJETO_CONTEXTO,
    R.ID_ASANA_PROJETO_BACKLOG,
    R.TITULO,
    R.DATA_INICIO,
    R.DATA_FIM,
    R.SITUACAO,
    COUNT(I.ID_ROADMAP_ITEM) AS TOTAL_CARDS,
    SUM(CASE WHEN I.CONCLUIDO = TRUE THEN 1 ELSE 0 END) AS CARDS_CONCLUIDOS,
    SUM(CASE WHEN I.CONCLUIDO = FALSE THEN 1 ELSE 0 END) AS CARDS_PENDENTES,
    CAST(
      CASE
        WHEN COUNT(I.ID_ROADMAP_ITEM) = 0 THEN 0
        ELSE (100.00 * SUM(CASE WHEN I.CONCLUIDO = TRUE THEN 1 ELSE 0 END)
              / COUNT(I.ID_ROADMAP_ITEM))
      END AS NUMERIC(6,2)
    ) AS PERCENTUAL_CONCLUSAO
FROM ROADMAPS R
LEFT JOIN ROADMAP_ITENS I
       ON I.ID_ROADMAP = R.ID_ROADMAP AND I.EXCLUIDO_EM IS NULL
WHERE R.EXCLUIDO_EM IS NULL
GROUP BY
    R.ID_ROADMAP, R.ID_USUARIO_GESTOR, R.ID_ASANA_EQUIPE,
    R.ID_ASANA_PROJETO_CONTEXTO, R.ID_ASANA_PROJETO_BACKLOG,
    R.TITULO, R.DATA_INICIO, R.DATA_FIM, R.SITUACAO;

