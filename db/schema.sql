CREATE VIEW VW_PROJETOS_PROGRESSO AS
SELECT
    P.ID_PROJETO,
    P.NOME,
    P.COR,
    P.ARQUIVADO,
    P.ID_ASANA_PROJETO,
    P.ID_USUARIO_CRIADOR,
    COUNT(V.ID_ROADMAP) AS TOTAL_ROADMAPS,
    SUM(CASE WHEN V.SITUACAO = 'CONCLUIDO' THEN 1 ELSE 0 END) AS ROADMAPS_CONCLUIDOS,
    SUM(CASE WHEN V.SITUACAO IN ('RASCUNHO', 'PLANEJADO', 'EM_ANDAMENTO', 'CONCLUSAO_PENDENTE')
             THEN 1 ELSE 0 END) AS ROADMAPS_ATIVOS,
    COALESCE(SUM(V.TOTAL_CARDS), 0) AS TOTAL_CARDS,
    COALESCE(SUM(V.CARDS_CONCLUIDOS), 0) AS CARDS_CONCLUIDOS,
    CAST(
      CASE
        WHEN COALESCE(SUM(V.TOTAL_CARDS), 0) = 0 THEN 0
        ELSE 100.00 * SUM(V.CARDS_CONCLUIDOS) / SUM(V.TOTAL_CARDS)
      END AS NUMERIC(6,2)
    ) AS PERCENTUAL_GERAL
FROM PROJETOS P
LEFT JOIN ROADMAPS R
       ON R.ID_PROJETO = P.ID_PROJETO AND R.EXCLUIDO_EM IS NULL
LEFT JOIN VW_ROADMAP_PROGRESSO V
       ON V.ID_ROADMAP = R.ID_ROADMAP
GROUP BY P.ID_PROJETO, P.NOME, P.COR, P.ARQUIVADO, P.ID_ASANA_PROJETO, P.ID_USUARIO_CRIADOR;

COMMIT;


