/* 1. USUARIOS E AUTENTICACAO                                        */
/* ================================================================ */

CREATE TABLE USUARIOS (
    ID_USUARIO              BIGINT GENERATED ALWAYS AS IDENTITY,
    NOME                    VARCHAR(150) NOT NULL,
    EMAIL                   VARCHAR(254) NOT NULL,
    SENHA_HASH              VARCHAR(255),
    AUTH_PROVEDOR           VARCHAR(50),
    AUTH_SUBJECT            VARCHAR(255),
    AVATAR_URL              VARCHAR(1000),
    EMAIL_NOTIFICACAO       VARCHAR(254),
    WHATSAPP_E164           VARCHAR(20),
    EMAIL_VERIFICADO_EM     TIMESTAMP,
    WHATSAPP_VERIFICADO_EM  TIMESTAMP,
    PERFIL                  VARCHAR(20) DEFAULT 'GESTOR' NOT NULL,
    ATIVO                   BOOLEAN DEFAULT TRUE NOT NULL,
    ULTIMO_LOGIN_EM         TIMESTAMP,
    CRIADO_EM               TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ATUALIZADO_EM           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_USUARIOS_AUTH UNIQUE (AUTH_PROVEDOR, AUTH_SUBJECT),
    CONSTRAINT CK_USUARIOS_PERFIL CHECK (PERFIL IN ('ADMIN', 'GESTOR', 'LEITOR'))
);

/* Refresh tokens da API. Guarda somente o hash SHA-256 do token. */
CREATE TABLE AUTH_SESSOES (
    ID_AUTH_SESSAO          BIGINT GENERATED ALWAYS AS IDENTITY,
    ID_USUARIO              BIGINT NOT NULL,
    TOKEN_HASH              VARCHAR(64) CHARACTER SET ASCII NOT NULL,
    USER_AGENT              VARCHAR(500),
    IP_ORIGEM               VARCHAR(64),
    EXPIRA_EM               TIMESTAMP NOT NULL,
    REVOGADO_EM             TIMESTAMP,
    CRIADO_EM               TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_AUTH_SESSOES PRIMARY KEY (ID_AUTH_SESSAO),
    CONSTRAINT FK_AUTH_SESSAO_USUARIO FOREIGN KEY (ID_USUARIO)
        REFERENCES USUARIOS (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT UK_AUTH_SESSAO_TOKEN UNIQUE (TOKEN_HASH)
);

/* state / PKCE / nonce dos fluxos OAuth (Google e Asana). Vida curta. */
