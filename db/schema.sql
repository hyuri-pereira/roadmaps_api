/* =====================================================================
   GERENCIADOR DE ROADMAP + ASANA
   Banco-alvo: Firebird 5.0 | SQL Dialect 3 | CHARACTER SET UTF8

   Script consolidado para BANCO NOVO. Nao e migracao.

   Premissas
   - Um roadmap pertence a um projeto de contexto do Asana.
   - Card marcado  => projeto SPRINT  / secao "A fazer".
   - Card desmarcado => projeto Backlog / secao "Refino".
   - O percentual e calculado pela view VW_ROADMAP_PROGRESSO; nao e armazenado.
   - Tokens e segredos so entram no banco ja cifrados pela aplicacao (AES-256-GCM).
   - Alteracoes externas chegam por webhook e/ou reconciliacao periodica.
   - Exclusoes/conclusoes remotas sao processadas pela fila INTEGRACAO_FILA.
   - Nenhuma trigger faz HTTP. Toda chamada externa e feita por workers.

   Periodo do roadmap: DATA_FIM entre 7 dias e 3 meses apos DATA_INICIO.

   ---------------------------------------------------------------------
   CORRECOES APLICADAS SOBRE A VERSAO ANTERIOR DO DDL
   1. Variavel V_ID de BIU_ROADMAPS agora e zerada antes de cada SELECT.
      Sem isso, um SELECT sem linhas preservava o valor anterior e a
      validacao de secao x projeto passava a comparar lixo.
   2. SP_SOLICITAR_CONCLUSAO_ROADMAP usava GEN_UUID() na CHAVE_IDEMPOTENCIA
      e depois testava se ela ja existia - o teste nunca era verdadeiro e
      cada clique no botao "Concluir" duplicava a fila. Agora a chave e
      deterministica (item + revisao).
   3. AIU_ITEM_FECHAR nao conclui mais roadmap em RASCUNHO.
   4. SP_MONTAR_CARD so escreve o bloco "Links de referencia:" quando
      existe ao menos uma referencia.
   5. UPDATE ROADMAPS SET REVISAO=REVISAO virou ATUALIZADO_EM, com o mesmo
      efeito de serializacao e intencao explicita.
   6. Tabelas novas exigidas pelo backend: AUTH_SESSOES (refresh token),
      OAUTH_ESTADOS (state/PKCE do Google e do Asana) e ASANA_SYNC_TOKENS.
   7. INTEGRACAO_FILA ganhou LOCK_TOKEN, para o worker so confirmar um job
      se ainda for o dono da lease.
   8. Indices adicionais de consulta (login por provedor, membresias,
      notificacoes, itens por roadmap).
   ===================================================================== */

SET SQL DIALECT 3;
SET NAMES UTF8;
SET AUTODDL OFF;

